import 'package:flutter/material.dart';

/// Tailwind-like design tokens for consistent spacing/radius/sizing.
/// Flutter does not use Tailwind CSS natively, so these tokens provide
/// a similar utility-first convention in Dart.
class AppTokens {
  AppTokens._();

  // Spacing
  static const double s0 = 0;
  static const double s1 = 4;
  static const double s2 = 8;
  static const double s3 = 12;
  static const double s4 = 16;
  static const double s5 = 20;
  static const double s6 = 24;
  static const double s8 = 32;
  static const double s10 = 40;
  static const double s12 = 48;
  static const double s16 = 64;
  static const double s20 = 80;

  // Radius
  static const double rSm = 8;
  static const double rMd = 12;
  static const double rLg = 16;
  static const double rXl = 20;
  static const double rFull = 999;

  static const BorderRadius radiusSm = BorderRadius.all(Radius.circular(rSm));
  static const BorderRadius radiusMd = BorderRadius.all(Radius.circular(rMd));
  static const BorderRadius radiusLg = BorderRadius.all(Radius.circular(rLg));
  static const BorderRadius radiusXl = BorderRadius.all(Radius.circular(rXl));

  // Layout
  static const double maxContentWidth = 1200;
  static const EdgeInsets pagePadding = EdgeInsets.symmetric(horizontal: 24);
}
